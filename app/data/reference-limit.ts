// 参考图上限相关的人话文案（三处出口共用一份：输入区阻断提示、上传/素材被拒、资产面板「继续修改」）。
//
// 为什么必须分开说：上限为 0 和"图太多"是两件事。上限 0 = 当前底模根本不收参考图
// （本地图片底模是文生图），此时提示"先删到 0 张"等于让用户把想改的那张图删掉。
// 2026-09-25 实测用户就卡在这里：创作页「继续修改」把产物设成参考图 → 发送按钮变灰 →
// 屏幕上只有一句「当前模型最多接受 0 张参考图，先删到 0 张或换一个支持多图的模型」。

/** 参考图被拒 / 超限时的一句话原因 */
export function referenceLimitReason(input: { max: number, modelName?: string, cloud?: boolean }): string {
  const name = input.modelName || '当前底模'
  if (input.max <= 0) {
    return input.cloud
      ? `${name} 不接受参考图，换一个支持参考图的模型再试。`
      : `${name} 是文生图，带不了参考图：想改这张图，先换成支持参考图的模型，或去「技能」里用改图工具。`
  }
  return `当前模型最多接受 ${input.max} 张参考图，先删到 ${input.max} 张或换一个支持多图的模型。`
}
